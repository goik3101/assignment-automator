// 조사 호출이 **JSON 대신 사람에게 말을 거는 답**을 돌려준 경우를 가려낸다.
//
// 왜(2026-11-12 실측, 사회 "경제적 유인" 얇은 경로): 조사 모델이 사실 배열 대신 이렇게 답했다 —
//   "검색을 시작해도 될까요? (자료는 한 번의 검색으로 … 사실 10–14개를 JSON 배열 형식으로 제공합니다.)"
// 검색은 **페이지 26곳을 이미 열었는데** 우리는 사실 0개로 읽고 조사 실패로 처리했다. 그러면 글쓰기가
// 예전 경로(stageA)로 떨어져 **출처 0개**가 되고, 그 경로가 23.5초를 두 번 썼다(총 47초).
// 즉 **한 번의 형식 실수가 출처 품질과 시간을 동시에 깎는다.**
//
// 고치는 쪽은 싸다: 같은 조사를 "질문하지 말고 JSON만" 한 줄 붙여 한 번 더 부른다(8~12초).
// 실패한 폴백(23.5초 × 2, 출처 0개)보다 싸고, 출처가 생긴다.
//
// alias import 없음 — node:test에서 바로 불러옴.

/** 사실을 못 읽었을 때, 그 답이 "형식을 어긴 것"인지(= 다시 물으면 될 것인지) 본다. */
export function looksLikeAskingPermission(text: string): boolean {
  const t = (text ?? "").trim();
  if (!t) return false;
  // JSON을 내려는 흔적이 조금이라도 있으면 형식 실수가 아니라 파싱 문제다(그건 다른 길로 고친다).
  if (/^[[{]/.test(t) || /"url"\s*:/.test(t)) return false;
  if (t.length > 1200) return false;
  return /(할까요|될까요|드릴까요|진행할까요|원하시면|알려\s*주시면|요청해\s*주시면|제공합니다|시작하겠습니다|시작할까요)/.test(t);
}

