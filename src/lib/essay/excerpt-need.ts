// 이 과제가 "책 속 인상 깊은 구절"처럼 원문 인용을 요구하는가. 요구하지 않으면 인용구 검색·원문 검증(100초 이상 걸리는 단계)을 돌리지 않는다.
// alias import 없음 — node:test에서 바로 불러올 수 있게.
// 문장 단위 인용도 원문 인용이다 — "책에서 한 문장을 인용하여", "문장을 골라 옮겨 쓰시오"(실측 2026-11-01 규칙 전수).
const EXCERPT_HINT =
  /구절|발췌|명대사|명문장|책\s*속\s*(?:한\s*)?문장|원문\s*(?:인용|구절|문장)|인상\s*깊(?:은|었던)\s*(?:문장|대목|장면\s*묘사)|문장[^.。\n]{0,12}(?:인용|옮겨\s*(?:적|쓰)|그대로\s*(?:적|쓰))|(?:인용|옮겨\s*적)[^.。\n]{0,8}문장/;

export function needsExcerpt(texts: string[]): boolean {
  return EXCERPT_HINT.test(texts.join(" "));
}
