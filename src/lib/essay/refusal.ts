// 제출할 글 안에서 AI가 "못 하겠다"고 밝히는 문장을 찾는다.
// 실측(2026-10-31, 사회 평가지 생성): "신문 기사 스크랩" 단계가 통째로 거절문이었다 —
// "신문 기사 원문이나 기사 링크가 제공되지 않아 … 확인할 수 없다. 확인되지 않은 기사 제목이나 출처를 만들어
//  스크랩처럼 제시하지는 않겠다. … 신문 기사 스크랩 요건을 충족하지 않는다."
// 날조 차단(2026-10-29)의 반작용이다. 지어내지 않는 것은 맞지만, 학생이 제출할 글에 거절문이 들어가면 안 된다 —
// 아는 사실로 뼈대를 쓰고 본인만 아는 칸만 비워야 한다(own-activity.ts의 빈칸 규칙과 같은 처리).
// alias import 없음 — node:test에서 바로 불러올 수 있게.

/** "쓰지 않겠다 / 쓸 수 없다"처럼 글쓰기를 거절하는 종결. */
// "기재할 수 없다"를 빼 두었다가 실측에서 새어 나갔다(2026-11-09, 사회 평가지 스크랩 칸):
// "현재 원고에 기사 원문과 제목·날짜·출처가 없어 원문 그대로 기재할 수 없다."가 제출 글에 그대로 들어갔다.
// 학생이 직접 채울 칸은 빈칸으로 두면 되는데, 못 하겠다는 말을 덧붙인 것이다.
const REFUSE =
  /(?:않겠다|않겠습니다|않으려\s*한다|제시하지는?\s*않|만들어\s*내지\s*않|지어내지\s*않|꾸미지\s*않|만들지\s*않|(?:쓸|작성할|제공할|답할|기재할|기입할|옮길|적을|넣을|채울|붙일|스크랩할|첨부할)\s*수\s*없)/;
/**
 * AI가 **학생에게 말을 거는** 문장("보내 주시면 정리해 드릴 수 있습니다"). 제출할 글에 들어가면 안 된다 —
 * 학생은 이 글을 선생님에게 낸다. 실측(2026-11-09, 사회 평가지): 거절문을 고치라고 한 보완이
 * 붙임 칸을 "기사 링크나 원문을 보내 주시면 … 정리해 드릴 수 있습니다."로 바꿔 놓았다.
 * 거절문과 달리 짝(자료 없음)을 요구하지 않는다 — 이 말투 자체가 제출 글에 있을 수 없다.
 */
const ADDRESSES_USER =
  /(?:보내|알려|올려|첨부해|제공해|입력해)\s*주(?:시면|시고|시기|세요|십시오)|드릴\s*수\s*있(?:습니다|다)|해\s*드리(?:겠|겠습니다|면)|도와\s*드리/;
/**
 * 자료가 없다는 서술. 단독으로는 거절이 아니다(연구 한계를 적는 문장일 수 있다).
 *
 * "원문이 없"처럼 **낱말이 바로 붙은 꼴만** 보다가 놓쳤다(실측 2026-11-09):
 * "기사 원문과 제목·날짜·출처가 **없어**"는 사이에 다른 말이 끼어 안 걸렸다. 자료를 가리키는 낱말과
 * "없다" 사이에 20자까지 끼어도 보게 한다 — 짝(REFUSE)이 같은 문장에 있어야 거절로 치므로 넓혀도 안전하다.
 */
const NO_MATERIAL =
  /(?:제공|주어지|첨부|입력|확인)(?:되지|지)\s*않(?:아|았|은)|주어진\s*자료(?:에는|로는|만으로)|(?:자료|원문|기사|본문|출처|링크|사진|이미지)[^.\n]{0,20}(?:가|이|은|는|도)\s*없(?:어|다|으므로|으니|기)/;
/** 과제 요건을 못 채웠다고 스스로 밝히는 문장. */
const UNMET = /요건(?:을|이)\s*충족하지\s*않|조건(?:을|이)\s*충족하지\s*못|요구(?:를|사항을)\s*충족하지\s*않/;

const sentences = (content: string) =>
  content
    .split("\n")
    .filter((l) => !/^\s*(?:#|\|)/.test(l))
    .flatMap((l) => l.split(/(?<=[.!?。](?:\[\d+\])*)\s+/))
    .map((s) => s.replace(/^\s*(?:[-*•]|\d+[.)])\s*/, "").trim())
    .filter((s) => s.length >= 10);

/** 제출할 글에 들어가면 안 되는 "못 하겠다" 문장들. */
export function findRefusalSentences(content: string): string[] {
  // 각주가 달린 문장은 조사로 확인한 **사실**이다 — 우리가 못 하겠다고 하는 말에는 출처가 붙지 않는다.
  // 전수 감사(2026-11-03, 저장된 결과물 173편): 걸린 4건이 전부 거짓이었다.
  //   "유튜브는 2009년 한국에서 인터넷 실명제를 별도로 도입하지 **않겠다**고 밝혔다.[5]" (제3자의 말)
  //   "유선 케이블에는 내장 마이크가 포함되지 않아 통화용 마이크를 **쓸 수 없다**.[3]" (제품 한계 서술)
  // 거짓 거절 하나가 그 단계를 통째로 다시 쓰게 만들어 오히려 품질을 깎는다 — 날조 검사기와 같은 처리.
  // 거절은 "자료가 없어서 못 쓰겠다"는 **한 쌍**으로 온다. "않겠다"만 보면 제3자의 말과 글쓰기 계획까지 걸린다:
  //   "유튜브가 한국식 실명제를 도입하지 않겠다고 밝힌 뒤 …"  (제3자가 한 말)
  //   "한쪽 주장만 나열하지 않으려 한다."                      (어떻게 쓸지 밝히는 계획)
  // 지어내기를 거부하는 말(지어내지 않겠다·꾸미지 않겠다)만은 그 자체로 거절이다 — 그건 우리가 하는 말이다.
  const SELF = /만들어\s*내지\s*않|지어내지\s*않|꾸미지\s*않/;
  return sentences(content).filter((s) => {
    if (/\[\d+\]/.test(s)) return false; // 각주가 달린 문장은 조사로 확인한 사실이다
    if (ADDRESSES_USER.test(s)) return true; // 학생에게 말을 거는 문장은 그 자체로 제출 글에 있을 수 없다
    if (SELF.test(s)) return true;
    const lacks = NO_MATERIAL.test(s) || UNMET.test(s);
    if (!lacks) return false;
    return REFUSE.test(s) || UNMET.test(s) || /확인할\s*수\s*없|알\s*수\s*없/.test(s);
  });
}

/** 그 단계만 다시 쓰게 하는 지시. */
export function refusalRepairText(found: string[], label: string): string {
  const quoted = found.slice(0, 2).map((s) => `"${s.slice(0, 50)}…"`).join(" / ");
  return (
    `"${label}" 단계에 과제를 못 하겠다고 밝히는 문장이 있다(${quoted}). 학생이 그대로 제출할 글이므로 이런 문장을 쓰지 말 것. ` +
    `자료가 모자라도 거절하지 말고, 조사 자료로 확인된 사실로 그 단계의 뼈대를 끝까지 쓸 것(무엇을 다루는지·확인된 사실·수치와 각주·정리 양식). ` +
    `학생 본인만 아는 것(기사 제목·날짜·신문사 이름, 직접 센 값, 본인 이름·지역)만 "[직접 작성: …]" 빈칸으로 남기고, 빈칸은 3개를 넘기지 말 것. ` +
    `없는 사실을 지어내지는 말 것. 다른 단계와 각주는 그대로 둘 것.`
  );
}
