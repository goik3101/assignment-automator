// 학생이 실제로 하지 않은 행동을 "했다"고 쓴 문장을 찾는다.
// 실측(2026-10-29, 사용자가 제출 직전까지 간 실제 결과물): 자료 수집 단계가 "오늘 수업 시간 중 스마트폰으로 … 화면을 촬영했다",
// "OECD 비교 통계를 캡처해 보관했다", "수행평가지에 각 사진 아래에 … 적었다"처럼 학생이 하지도 않은 활동을 1인칭 과거형으로 지어냈다.
// 그대로 제출하면 거짓 기록이 되므로 글 품질이 아니라 신뢰 문제다. 프롬프트에 금지 규칙이 있어도 나왔으므로 코드로도 센다.
// 오탐이 더 해로우니 "학생만 할 수 있는 물리적 행동"의 과거형만 본다 — "확인했다·기록했다·분석했다"처럼 글에서도 자연스러운 말은 넣지 않는다.
// alias import 없음 — node:test에서 바로 불러올 수 있게.

/** 학생이 몸으로 해야 하는 일. 이 말이 있고 문장이 과거형으로 끝나면 "했다고 지어낸 것"으로 본다. */
// "방문자 수"는 학생이 간 것이 아니다 — 낱말 뒤를 보고 가른다(실측: "일평균 방문자 기준이 낮아진" 문장이 날조로 잡혔다).
// `인쇄`만은 **단독으로 두면 안 된다** — 실측(2026-11-10, 영어 발명품): "구텐베르크 활자 인쇄기는 …
// 인쇄하는 데 쓰였다", "구텐베르크는 1448년경부터 금속 활자를 이용한 인쇄를 실험했다"가 전부 날조로 잡혔다.
// **인쇄는 과제의 주제가 될 수 있다**(인쇄기·인쇄술). 학생이 하는 인쇄는 붙이는 말과 짝으로 온다.
// `사진·그림·도구 … 준비`는 2026-11-14 역사-03에서 "사진은 … 총 4장을 준비했다"가 통과해 추가했다 — 사진은 학생이 가정에서 준비하는 것이다(안내문).
// `출력`은 주제가 되는 일이 드물어 그대로 둔다("기사 제목과 날짜가 보이게 출력했다"는 학생이 한 일이다).
const OWN_ACTION =
  /촬영|캡처|캡쳐|스크랩|출력|부착|첨부|오려|사진을?\s*찍|붙여|붙이|방문(?!자|객|률|율|기록)|인터뷰|설문|인쇄[^.\n]{0,20}(?:붙|부착|첨부|스크랩|오려|제출)|(?:사진|그림|채색\s*도구|준비물)[^.\n]{0,40}준비/;
/** 과거·완료 어미. 현재형("촬영한다", "붙인다")은 계획·설명이라 건드리지 않는다. */
const PAST = /(?:했|였|었|았|뒀)(?:다|고|으며|음)|두었다|찍었다|붙였다/;
/**
 * 지어낸 것임을 **글이 스스로 밝힌** 문장은 거짓 기록이 아니다.
 *
 * 실측(2026-11-09, 역사 신문 13회 중 날조 1건이 매번 이것이었다):
 *   "인터뷰 대상: 해방 뒤 남한에서 새 정부의 출범을 지켜본 시민을 가상 인물로 설정했다."
 * 역사 신문의 인터뷰는 **가상 인터뷰가 정답**이고(그 시대 사람을 실제로 만날 수 없다),
 * 문장은 "가상 인물"이라고 분명히 밝혔다. 그런데 "인터뷰"(OWN_ACTION) + "설정했다"(PAST)에 걸려
 * 거짓 경고가 떴고, 보완이 돌면 **멀쩡한 인터뷰 칸을 다시 쓰게** 된다.
 * 지어낸 것을 지어냈다고 적는 것은 우리가 바라는 바라서, 그 표시가 있으면 통과시킨다.
 */
const IMAGINED = /가상|상상|가정하|가정한|가정해|모의|예시로/;
/**
 * 각주·근거 번호를 어떻게 붙였는지 말하는 문장은 **작업 메모**다 — 학생이 몸으로 한 일이 아니다.
 * 실측(저장된 결과물 235편 전수): 날조로 잡힌 12건 중 8건이 이것이었다
 * ("각 주장에는 해당 사실의 근거 번호를 붙여 … 정리했다", "각주 형태로 번호를 붙여 나타내었다").
 * 이 문장들은 제출 글에서 빠져야 하지만, 그것을 맡는 검사기는 따로 있다(쓰임 설명·작업 메모 제거).
 * 여기서 날조로 잡으면 멀쩡한 단계를 "지어낸 활동"이라며 다시 쓰게 된다.
 */
const PROCESS_NOTE = /근거\s*번호|각주|인용\s*번호|출처\s*번호|번호를\s*붙여|번호로\s*연결/;
/**
 * 조사로 확인한 설문·인터뷰를 **인용한** 문장("…설문에서 응답자의 80%가 찬성했다")은 사실 서술이다.
 * 각주가 빠져 있으면 그것은 무각주 수치 쪽에서 잡는다 — 학생이 설문을 돌렸다는 거짓 기록이 아니다.
 */
const CITED_SURVEY = /(?:설문|여론\s*조사|조사|인터뷰)(?:조사)?\s*에서/;
/** 주어가 학생이 아닌 문장(기관·매체·연구가 한 일)은 사실 서술이다. */
const THIRD_PARTY =
  /(?:정부|부처|청|위원회|기관|연구(?:진|팀|소)?|학회|대학|신문|언론|방송|기자|기사|보도|보고서|자료|기업|회사|협회|재단|단체|경찰|법원|헌법재판소|통계청|보건복지부|교육청)(?:는|은|이|가|에서|에서는|에 따르면)/;

/**
 * 절 단위로 본다 — "보건복지부가 발표를 확인했고, 해당 화면을 촬영했다"처럼 앞 절의 주어가 기관이어도
 * 촬영한 것은 학생이다. 행동이 들어 있는 절에 기관 주어가 없으면 학생이 한 일로 본다.
 */
export function isOwnActivitySentence(sentence: string): boolean {
  // 각주가 달린 문장은 **조사로 확인한 사실**이다 — 학생이 한 일에는 출처가 붙지 않는다.
  // 실측(2026-11-03, 역사 신문): "유엔 위원단이 북한 지역을 방문하지 못하면서…[2]"가 학생 행동으로 잡혔다.
  // THIRD_PARTY는 손으로 적은 낱말 목록이라 "위원단"·"소총회"처럼 빠진 말이 계속 나온다 —
  // 낱말을 더 넣는 대신, 우리가 붙인 각주라는 일반 신호를 쓴다. 거짓 경고는 멀쩡한 단계를 다시 쓰게 만든다.
  if (/\[\d+\]/.test(sentence)) return false;
  const s = sentence.trim();
  if (!s) return false;
  const clauses = s.split(/,\s*|(?<=[가-힣])고\s+/);
  return clauses.some(
    (c) => OWN_ACTION.test(c) && PAST.test(c) && !THIRD_PARTY.test(c) && !IMAGINED.test(c) && !PROCESS_NOTE.test(c) && !CITED_SURVEY.test(c)
  );
}

/** 글에서 학생 행동을 지어낸 문장을 모은다(소제목·표 줄은 제외). */
export function findOwnActivitySentences(content: string): string[] {
  const out: string[] = [];
  for (const line of content.split("\n")) {
    if (/^\s*(?:#|\|)/.test(line)) continue;
    // 각주가 문장 끝 마침표 뒤에 붙는("…유물이다.[1] 다음 문장") 글에서 문장이 합쳐지지 않게 각주까지 앞 문장으로 본다.
    for (const sentence of line.split(/(?<=[.!?。](?:\[\d+(?:,\s*\d+)*\])*)\s+/)) {
      const s = sentence.replace(/^\s*(?:[-*•]|\d+[.)])\s*/, "").trim();
      if (s.length >= 8 && isOwnActivitySentence(s)) out.push(s);
    }
  }
  return out;
}

/** 학생이 직접 수행한 것을 적는 단계인가(자료 수집·조사 기록·관찰 활동지). 이런 단계만 빈칸 규칙을 적용한다. */
const OWN_RECORD_LABEL =
  /자료\s*수집|수집\s*(?:및|과|·)?\s*기록|조사\s*(?:및|과|·)?\s*기록|관찰\s*기록|기록지|활동지|활동\s*기록|행동\s*기록|(?:협업|활용|사용)\s*과정\s*기록|사용\s*기록|(?:AI|챗봇|챗지피티|ChatGPT)[^\n]{0,12}기록|탐구\s*일지|취재/i;
const OWN_RECORD_DESC = /(?:직접|스스로)\s*(?:조사|수집|관찰|촬영|기록)|수행평가지에\s*(?:붙|적|기록)/;
export function isOwnRecordStep(el: { label: string; description?: string }): boolean {
  return OWN_RECORD_LABEL.test(el.label) || OWN_RECORD_DESC.test(el.description ?? "");
}

const BLANK = /\[직접\s*작성[^\]]*\]/g;
export function countBlanks(content: string): number {
  return (content.match(BLANK) ?? []).length;
}

/** 빈칸이 너무 많을 때 줄 보완 지시 — 본인만 아는 것만 남기고 나머지는 채우게 한다. */
export function blankOveruseRepairText(max: number, found: number): string {
  return (
    `"[직접 작성: …]" 빈칸이 ${found}개나 된다(최대 ${max}개). 빈칸은 학생 본인만 알 수 있는 것(이름, 사는 지역·학교, 조사한 날짜, ` +
    `본인이 직접 센 값, 설문에 응한 사람 수)에만 남기고, 나머지 빈칸은 실제 내용으로 채울 것 — 어떤 자료를 어디서 찾는지(기관·자료 이름), ` +
    `조사 방법과 순서, 설문·인터뷰 문항 초안, 자료가 보여 주는 사실과 수치는 빈칸이 아니라 글로 쓴다. 다른 문장과 각주는 그대로 둘 것.`
  );
}

/** 걸린 단계에 줄 보완 지시(이미 있는 "그 단계만 고치기" 경로로 전달한다). */
export function ownActivityRepairText(sentences: string[]): string {
  const quoted = sentences.slice(0, 3).map((s) => `"${s.slice(0, 60)}…"`).join(" / ");
  return (
    `학생이 실제로 하지 않은 행동을 한 것처럼 쓴 문장이 있다(${quoted}). ` +
    `사진 촬영·캡처·스크랩·출력·부착·방문·인터뷰는 학생이 직접 하는 일이라 AI가 "했다"고 쓸 수 없다. ` +
    `그 문장들은 자료의 내용(자료 이름·출처 기관·사실·수치)과 할 일의 방법을 쓰는 문장으로 바꾸고("~에서 ~를 확인한다"), ` +
    `빈칸("[직접 작성: 무엇]")은 학생 본인만 알 수 있는 것(이름·사는 지역·조사한 날짜·본인이 직접 센 값)에만 남길 것. ` +
    `다른 문장과 사실(연도·수치·각주 번호)은 그대로 둘 것.`
  );
}

/**
 * 보완(모델 재작성) 뒤에도 남은 **지어낸 행동 문장을 코드가 지운다.**
 *
 * 왜(2026-11-15, 거대 안내문 점검 역사-03·사회-04): 정직성 보완은 시간 예산을 무시하고 한 번 도는데도 모델이 문장을 그대로 두는 실행이 있었다
 * ("각 유물마다 사진을 한 장씩 따로 준비해 첨부했다", "수업 중 스마트폰으로 관련 자료를 검색하고,") — 재작성 길이가 699→698자로 사실상 안 바뀌었다.
 * 모델에게 또 시키는 길은 이 프로젝트에서 반복해서 실패했고, 이 검사기는 오탐을 12건에서 0건으로 줄여 둔 상태라 **걸린 문장을 지워도 되는 정밀도**다.
 * 지운 뒤 글이 40자 미만으로 줄면 지우지 않는다(칸이 비는 쪽이 더 나쁘다).
 */
export function removeOwnActivitySentences(content: string): { content: string; removed: string[] } {
  // 학생이 몸으로 하는 일 중에서도 **사진·화면·스마트폰 자료 수집**만 지운다 — "인터뷰했다·방문했다"는 가상 회고록·일기 같은 글에서 정상이다.
  const STRONG = /(?:사진|그림|화면|자료)[^.\n]{0,40}(?:준비|촬영|첨부|캡처|캡쳐|부착|붙)|스마트폰으로[^.\n]{0,40}(?:검색|촬영|찾|확인)|수업\s*(?:중|시간)[^.\n]{0,30}(?:촬영|캡처|검색)/;
  const found = findOwnActivitySentences(content).filter((s) => STRONG.test(s));
  if (found.length === 0) return { content, removed: [] };
  let next = content;
  const removed: string[] = [];
  for (const s of found) {
    if (!next.includes(s)) continue;
    const cut = next.replace(s, "").replace(/[ \t]{2,}/g, " ").replace(/^[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n");
    if (cut.replace(/\s/g, "").length < 40) continue;
    next = cut;
    removed.push(s);
  }
  return { content: next.replace(/[ \t]+$/gm, ""), removed };
}
