// 학생이 읽은 책이 **어떤 형태의 책인지**(만화·그림책·소설…)를 조사로 확인된 사실에서만 읽는다.
//
// 왜(실측 2026-11-03, 역사 카드뉴스): 사용자의 최소 통과 기준 4번이 "그림을 너무 복잡하게 안 그리고
// **책에 맞게** 그렸는가"다. 《사일구》는 '만화로 보는 민주화운동' 시리즈의 만화책인데, 결과물의 그림 묘사는
// 실사 사진 같은 장면이었다(3회 중 '만화'라는 말이 1회·0회). 만화책을 읽고 만드는 카드뉴스라면
// 그림도 만화의 한 컷처럼 그릴 수 있게 알려 줘야 한다.
//
// **책을 읽을 수는 없다.** 그래서 형태만 쓰고 장면·대사는 절대 지어내지 않는다 — 형태는 서지 조사로 확인된다.
// alias import 없음 — node:test에서 바로 불러올 수 있게.

/** 그림을 어떻게 그릴지 달라지는 형태만 본다(소설·수필은 그림 지시가 달라지지 않아 넣지 않는다). */
const FORMS: [RegExp, string][] = [
  [/만화로\s*보는|만화책|그래픽\s*노블|웹툰|카툰|(?<![가-힣])만화(?![화가])/, "만화"],
  [/그림책|그림\s*동화/, "그림책"],
  [/사진집|포토\s*에세이/, "사진집"],
  [/시집(?![가-힣])/, "시집"],
];

export interface BookFormFact {
  text?: string;
  title?: string;
}

/**
 * 조사 노트의 사실들에서 이 책의 형태를 찾는다. 책 제목이 함께 나오는 사실만 본다
 * (다른 책 이야기에 걸리지 않게). 못 찾으면 null — 그러면 아무 지시도 더하지 않는다.
 */
export function bookForm(facts: BookFormFact[], title: string): string | null {
  const key = title.replace(/\s/g, "").toLowerCase();
  if (!key) return null;
  for (const f of facts) {
    const text = `${f.text ?? ""} ${f.title ?? ""}`;
    if (!text.replace(/\s/g, "").toLowerCase().includes(key)) continue;
    for (const [re, name] of FORMS) if (re.test(text)) return name;
  }
  return null;
}

/** 그림을 그려야 하는 산출물에만 붙이는 한 줄. 형태를 모르면 빈 문자열. */
export function bookFormBlock(form: string | null, title: string): string {
  if (!form) return "";
  const how =
    form === "만화"
      ? "칸의 그림은 만화의 한 컷처럼 묘사할 것(인물 표정과 말풍선 한두 개, 단순한 배경)."
      : form === "그림책"
        ? "칸의 그림은 그림책의 한 장면처럼 묘사할 것(큰 인물 하나와 단순한 배경)."
        : form === "사진집"
          ? "칸의 그림은 사진 한 장을 옮겨 그리듯 묘사할 것(한 장면, 군더더기 없이)."
          : "칸의 그림은 그 책의 분위기에 맞게 단순하게 묘사할 것.";
  return `\n【읽은 책의 형태 — 그림 묘사에 반영할 것】 학생이 읽은 『${title}』은 ${form}이다. ${how} 다만 **그 책에 실제로 있는 장면·대사·그림을 본 것처럼 지어내지 말 것** — 책을 확인하지 않았다. 사건의 내용을 ${form}의 그림으로 어떻게 보여줄지만 적는다.\n`;
}

/** 안내문이 "읽은 책에 대한 활동"이라고 말하는가(독후 활동·독서 감상·책을 읽고). */
// "《사일구》를 읽고 … 만들기"처럼 **작품 이름 뒤의 "읽고/읽었다"**가 가장 흔하다 — 분석의 주제에도,
// 학생이 적은 지침("책: 윤태호 작가의 《사일구》를 읽었다")에도 그렇게 적힌다. 실측(2026-11-09): "읽었다"를
// 빼 두었다가 세 번 돌리는 동안 블록이 한 번도 안 붙었다.
// 다만 "기사를 읽고", "지문을 읽고"는 책이 아니다 — 책·도서·따옴표 제목 뒤일 때만 본다.
const READING_ACTIVITY =
  /독후\s*활동|독서\s*(?:활동|감상|기록)|읽은\s*책|(?:책|도서|《[^》]{1,40}》|『[^』]{1,40}』|「[^」]{1,40}」)\s*(?:[(（][^)）]{0,30}[)）])?\s*(?:을|를)?\s*읽(?:고|었|은)|읽고\s*(?:나서|난\s*뒤)/;

export function isReadingActivity(texts: (string | undefined)[]): boolean {
  return texts.some((t) => t && READING_ACTIVITY.test(t.replace(/\s+/g, " ")));
}

/**
 * 독후 활동인데 결과물이 **일반 역사·사회 서술**로만 채워지는 것을 막는 블록.
 *
 * 실측(2026-11-09, 카드뉴스 결과물 13편 중 채점된 5편): 책 언급 횟수가 점수를 갈랐다 —
 * 7회 → 9/9·8/9, 5회 → 7/9, 4회 → 6/9, 3회 → 7/9. 떨어진 실행의 실패 항목이 바로
 * "학생이 읽은 그 책의 내용을 다룬다(일반 역사 서술로 바뀌지 않았다)"였다.
 * 조사가 책 사실을 모아 와도 글쓰기가 각주 달린 사건 사실을 더 편하게 쓰기 때문이다.
 *
 * 지어내지 않게 선을 긋는다: 책에서 **확인된 것**(제목·작가·주인공·형태)만 쓰고,
 * 확인 안 된 장면·대사는 "이 책의 시선으로"처럼 관점으로만 쓴다.
 */
export function bookThreadBlock(title: string, cells: number): string {
  if (!title) return "";
  const half = Math.max(2, Math.ceil(cells / 2));
  return (
    `\n【읽은 책에 대한 활동 — 반드시 지킬 것】 이 과제는 학생이 읽은 『${title}』에 대한 활동이다. ` +
    `사건만 설명하면 "그 책을 읽었다"는 것이 글에서 사라진다. ` +
    `${cells > 1 ? `칸이 ${cells}개라면 **적어도 ${half}칸**에서` : "글 곳곳에서"} 이 책의 인물·시선·이야기가 드러나게 쓸 것 ` +
    `(예: 그 책이 따라가는 인물의 눈으로 그 장면을 본다). ` +
    `다만 **조사로 확인되지 않은 장면·대사·쪽수를 지어내지 말 것** — 책을 직접 읽은 것은 학생이고 너는 아니다.\n`
  );
}
